#!/bin/sh
# First-boot WordPress setup, run once by the wp-cli service — installs
# WordPress core (idempotent: skipped if already installed, so re-running
# this container after a restart is harmless), activates ACF (an mu-plugin
# auto-loads with no activation step, but ACF itself is a REAL plugin and
# needs one), and switches on pretty permalinks (the custom post types'
# rest_base routes and the public site's own URLs both expect them).
#
# What this does NOT do: generate the WORDPRESS_SCHEDULER_APP_PASSWORD
# webx-studio needs. WordPress Application Passwords can't be set to a
# chosen value — only generated by WordPress itself — so that step stays
# manual: log into wp-admin as the account created below, then
# Users -> Profile -> Application Passwords, exactly as NewWorkspace.tsx's
# own in-app instructions already say for any new WordPress-engine tenant.
set -eu
WP="wp --path=/var/www/html --allow-root"

echo "[wp-bootstrap] waiting for wp-config.php (written by the wordpress service's own entrypoint)..."
until [ -f /var/www/html/wp-config.php ]; do sleep 2; done

echo "[wp-bootstrap] waiting for the database..."
until $WP db check >/dev/null 2>&1; do sleep 3; done

if $WP core is-installed >/dev/null 2>&1; then
  echo "[wp-bootstrap] already installed — skipping core install."
else
  echo "[wp-bootstrap] installing WordPress core..."
  $WP core install \
    --url="${WP_SITE_URL:?set WP_SITE_URL}" \
    --title="${WP_SITE_TITLE:-WebX WordPress}" \
    --admin_user="${WORDPRESS_SCHEDULER_USERNAME:?set WORDPRESS_SCHEDULER_USERNAME}" \
    --admin_password="${WP_ADMIN_PASSWORD:?set WP_ADMIN_PASSWORD}" \
    --admin_email="${WP_ADMIN_EMAIL:?set WP_ADMIN_EMAIL}" \
    --skip-email
fi

echo "[wp-bootstrap] activating ACF..."
$WP plugin activate advanced-custom-fields

echo "[wp-bootstrap] activating the custom theme (TOR gap audit)..."
$WP theme activate webx-theme

echo "[wp-bootstrap] setting pretty permalinks..."
$WP rewrite structure '/%postname%/'
$WP rewrite flush

echo "[wp-bootstrap] done. Next manual step (WordPress can't do this non-interactively):"
echo "[wp-bootstrap]   log into ${WP_SITE_URL}/wp-admin as ${WORDPRESS_SCHEDULER_USERNAME}, then"
echo "[wp-bootstrap]   Users -> Profile -> Application Passwords -> create one, and set it as"
echo "[wp-bootstrap]   WORDPRESS_SCHEDULER_APP_PASSWORD in this deployment's .env, then restart webx."
